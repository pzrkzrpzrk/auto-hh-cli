// Контракт промпта сопроводительного письма (Domain Service).
//
// Раньше тексты были размазаны по cover-letter.ts (одиночный запрос) и system-text.ts
// (пачка). Теперь это чистый домен: только строки промпта, ни портов, ни логов.
import { CoverSignature } from "@/domain/cover-letter/CoverSignature.js";
import type { Vacancy } from "@/domain/models.js";
import { stripHtml } from "@/shared/text-utils.js";

/** Добавка к системному тексту пачки, когда у каждой вакансии своё адаптированное резюме. */
const ADAPTED_NOTE =
  '\n\nДля каждой вакансии передано адаптированное под неё резюме — учитывай его при составлении письма, указывая релевантный опыт.';

export class CoverLetterPrompt {
  private readonly signature: CoverSignature;

  constructor(
    private readonly profile: string,
    signature?: string | CoverSignature,
  ) {
    this.signature = signature instanceof CoverSignature ? signature : new CoverSignature(signature);
  }

  /** Системный текст одиночного письма. */
  system(): string {
    return `Ты помогаешь соискателю писать сопроводительные письма для откликов на hh.ru. Профиль соискателя: ${this.profile}\n\nПиши лаконично, по-человечески, без канцелярита. Цель — убедить рекрутера открыть резюме.`;
  }

  /** Пользовательское сообщение для одной вакансии; resumeText — блок резюме, если он нужен. */
  singleUser(vacancy: Vacancy, resumeText: string | null = null): string {
    const description = stripHtml(vacancy.description).slice(0, 1000);
    const skills = (vacancy.key_skills || []).map(s => s.name).join(', ');
    const signature = this.signature.text;

    return `${resumeText ? `${resumeText}\n\n` : ''}Вакансия: ${vacancy.name}
Компания: ${vacancy.employer?.name || '—'}
Регион: ${vacancy.area?.name || '—'}
Ключевые навыки: ${skills || '—'}

Описание:
${description}

Напиши короткое сопроводительное письмо от моего имени в официально-деловом стиле. 3–5 предложений.

Образец:
"""
Здравствуйте! Заинтересовала вакансия в вашей компании — профиль полностью совпадает с моим опытом. Последние несколько лет работаю с React и NestJS, уверенно владею SQL/ORM, есть опыт с Next.js и SSR. Буду рад обсудить детали на созвоне.
${signature}
"""

Правила:
- Официально-деловой, нейтрально-вежливый тон. Полные предложения, грамотный русский.
- Никакой разговорности, сленга, сокращений ("прям", "трогал", "подшаманивал" и т.п.).
- Избегай канцеляритных штампов ("рассмотрите мою кандидатуру", "готов внести вклад в развитие"): пиши по делу, но корректно.
- Начни с "Здравствуйте!".
- 1–2 конкретных совпадения из описания вакансии.
- Без markdown, без "С уважением", без имени в подписи.
- Заверши строкой "${signature}".
- Не упоминай зарплату, вилку, ожидания по доходу — ни конкретных цифр, ни общих формулировок ("по рынку", "обсуждаемо" и т.п.).
- Не пиши "Заинтересовала вакансия <название компании>", а пиши "заинтересовала ваша вакансия" или "вакансия в вашей компании".
- Не используй длинные тире.
- Начинай основную часть с указания, что стек и задачи полностью подходят под твой профиль (например: "стек и задачи полностью совпадают с моим опытом", "профиль вакансии полностью соответствует моему стеку").`;
  }

  /** Системный текст пачки: те же правила плюс формат ответа {"letters": [...]}. */
  batchSystem(adapted: boolean): string {
    const signature = this.signature.text;
    const base = `Ты — ассистент, который помогает соискателю составлять короткие сопроводительные письма для откликов на вакансии.
Профиль соискателя: ${this.profile}
Твоя задача — для каждой вакансии из входных данных написать сопроводительное письмо от первого лица в официально-деловом стиле, объёмом 4–5 предложений.

Строгие правила:
- Начинай с обращения "Здравствуйте!".
- Официально-деловой, нейтрально-вежливый тон. Только полные предложения, грамотный русский язык. Без разговорных выражений и сленга.
- Избегай канцелярских штампов: не используй фразы вроде "рассмотрите мою кандидатуру", "готов внести вклад в развитие", "являюсь высококвалифицированным специалистом" и подобные клише. Пиши по существу, сдержанно и корректно.
- Обязательно укажи 1–2 конкретных совпадения между опытом из профиля соискателя и требованиями/обязанностями из описания вакансии. Бери только то, что действительно указано в профиле.
- Не используй markdown.
- Завершай письмо строкой "${signature}", без подписи, без "С уважением", без имени.
- Не добавляй никаких пояснений или комментариев.
- Не упоминай зарплату, вилку, ожидания по доходу — ни конкретных цифр, ни общих формулировок.
- Не пиши "Заинтересовала вакансия <название компании>", а пиши "заинтересовала ваша вакансия" или "вакансия в вашей компании".
- Не используй длинные тире.
- Начинай основную часть с указания, что стек и задачи полностью подходят под твой профиль (например: "стек и задачи полностью совпадают с моим опытом", "профиль вакансии полностью соответствует моему стеку").

Формат ответа — строго валидный JSON без какого-либо markdown-форматирования (без \`\`\`json и подобного):
{"letters": [{"vacancyId": "id вакансии", "coverLetter": "текст письма"}, ...]}`;
    return base + (adapted ? ADAPTED_NOTE : '');
  }

  /** Блок вакансии пачки: нумерация с 1, как в прежнем formatVacancyShort. */
  vacancySection(vacancy: Vacancy, order: number): string {
    return `=== ВАКАНСИЯ #${order} ===\n${this.vacancyText(vacancy)}`;
  }

  /** Короткая карточка для письма: описание обрезано до 1000 символов. */
  private vacancyText(vacancy: Vacancy): string {
    const description = stripHtml(vacancy.description).slice(0, 1000);
    const skills = (vacancy.key_skills || []).map(s => s.name).join(', ');
    return `vacancyId: ${vacancy.id}
Название: ${vacancy.name}
Компания: ${vacancy.employer?.name || '—'}
Регион: ${vacancy.area?.name || '—'}
Ключевые навыки: ${skills || '—'}
Описание:
${description}`;
  }
}
